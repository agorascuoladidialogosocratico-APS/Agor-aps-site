import assert from 'node:assert/strict';
import worker from '../src/worker.js';
const origin='https://agora-scuoladidialogosocraticoecittadinanzattiva.site';
const sends=[];
const env={CONTACT_EMAIL:{async send(payload){sends.push(payload);}},ASSETS:{async fetch(){return new Response('Asset',{status:200});}}};
const payload={name:'Persona di prova',email:'prova@example.org',topic:'Informazioni generali',message:'Vorrei conoscere le attività dell’associazione e il calendario dei prossimi incontri.',consent:true,website:''};
const post=(data,extra={},options={})=>worker.fetch(new Request(origin+'/api/contact',{method:'POST',headers:{'Content-Type':'application/json','Origin':origin,...extra},body:JSON.stringify(data)}),options.env||env);
const success=await post(payload);assert.equal(success.status,200);assert.equal((await success.json()).ok,true);assert.equal(sends.length,1);
assert.equal(sends[0].to,'agora.scuoladidialogosocratico@gmail.com');
assert.match(sends[0].text,/Persona di prova/);
assert.match(sends[0].text,/prova@example.org/);
let r=await post({...payload,email:'indirizzo-errato'});assert.equal(r.status,422);assert.equal(sends.length,1);
r=await post({...payload,consent:false});assert.equal(r.status,422);
r=await post({...payload,message:'troppo breve'});assert.equal(r.status,422);
r=await post({...payload,website:'bot.example'});assert.equal(r.status,200);assert.equal(sends.length,1);
r=await post(payload,{'Origin':'https://attacker.example'});assert.equal(r.status,403);
r=await post(payload,{}, {env:{ASSETS:env.ASSETS}});assert.equal(r.status,503);
r=await worker.fetch(new Request(origin+'/api/contact',{method:'GET'}),env);assert.equal(r.status,405);
r=await worker.fetch(new Request(origin+'/api/missing',{method:'GET'}),env);assert.equal(r.status,404);
r=await worker.fetch(new Request(origin+'/contatti/'),env);assert.equal(r.status,200);
console.log('Agorà contact endpoint: test di invio mock, validazione e protezione superati.');
