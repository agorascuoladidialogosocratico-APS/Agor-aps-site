import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
const read=p=>readFileSync(p,'utf8');
const home=read('index.html'),logic=read('assets/cinematic-overture.js');
const style=read('assets/cinematic-overture.css'),bundle=read('assets/agora-home.css');
const workflow=read('.github/workflows/publish-cms.yml');
const build=read('scripts/bundle-home-css.mjs');
assert.equal((home.match(/class="agora-overture"/g)||[]).length,1,'Exactly one opening stage required');
assert.equal((home.match(/class="agora-overture-skip"/g)||[]).length,1,'One accessible intro skip');
assert.ok(home.includes('sessionStorage.setItem('),'Remember played intro per session');
assert.ok(home.includes('prefers-reduced-motion: reduce'),'Reduced motion should never see intro');
assert.ok(home.includes('data-fallback-src="https://upload.wikimedia.org/'),'Art must have verified source fallback');
assert.ok(home.includes('src="/assets/cinema-raphael-detail.webp"'),'Use local high-definition artwork');
assert.ok(!home.includes('src="/assets/cinema-plato.png"'),'No tiny Plato cutout');
assert.ok(!home.includes('src="/assets/cinema-aristotle.png"'),'No tiny Aristotle cutout');
assert.ok(home.includes('https://commons.wikimedia.org/wiki/File:Raffael_058FXD.jpg'),'Artwork provenance missing');
assert.ok(home.includes('src="/assets/cinematic-overture.js?'),'Intro runtime missing');
assert.ok(logic.includes("setTimeout(finish,2600)"),'Opening should terminate automatically in <3 seconds');
assert.ok(logic.includes("skip.addEventListener('click',finish"),'Skip intro must work');
assert.ok(logic.includes("if(scrollY>12)finish()"),'Manual scroll must terminate intro');
assert.ok(logic.includes("if(event.persisted)finish()"),'BFCache must not replay intro');
assert.ok(logic.includes("painting.addEventListener('error'"),'Art fallback must work');
assert.ok(style.includes('AGORA_OVERTURE_V4'),'Intro CSS missing');
assert.ok(style.includes('pointer-events:none'),'Opening must not intercept interaction');
assert.ok(style.includes('prefers-reduced-motion:reduce'),'Reduced-motion CSS required');
assert.ok(style.includes('@keyframes agora-curtain-left'),'Left curtain scene missing');
assert.ok(style.includes('@keyframes agora-curtain-right'),'Right curtain scene missing');
assert.ok(build.includes("'assets/cinematic-overture.css'"),'Bundler must include new stage');
assert.ok(bundle.includes('/* SOURCE: assets/cinematic-overture.css */'),'Homepage bundle not updated');
assert.ok(workflow.includes('scripts/generate-cinematic-mural.py'),'CI high-res image generation missing');
assert.ok(workflow.includes('git add assets/cinema-raphael-detail.webp'),'High-res artwork must be published');
assert.ok(existsSync('scripts/generate-cinematic-mural.py'),'Source artwork renderer absent');
assert.ok(home.includes('class="book-stage"')&&home.includes('class="book-index"'),'Book must remain intact');
assert.ok(!home.includes('class="cinema-progress-track"'),'White bar must remain removed');
assert.ok(!home.includes('#193b4a'),'Petrol blue must remain absent');
for(const f of ['assets/cinematic-overture.js','assets/cinematic-agora.js'])
 execFileSync(process.execPath,['--check',f],{stdio:'pipe'});
console.log('Agorà overture: one-time <3s curtain, full-resolution fresco, fallbacks, native scroll and book retained.');
