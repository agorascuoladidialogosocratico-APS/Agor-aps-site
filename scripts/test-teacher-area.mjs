import assert from 'node:assert/strict';
import {handleTeacherArea} from '../src/teacher-area.js';
const base='https://agora-scuoladidialogosocraticoecittadinanzattiva.site';
const path='/area-docenti/cornaredo/';
const pass='not-a-real-secret-for-testing-only-482973590104';
const env={ERASMUS_DAVINCI_PASSWORD:pass};
const req=(p,opts={})=>new Request(base+p,opts);
const submit=(password,origin=base)=>req(path+'login',{method:'POST',headers:{'Content-Type':'application/x-www-form-urlencoded','Origin':origin,'Sec-Fetch-Site':'same-origin'},body:new URLSearchParams({password}).toString()});
let r=await handleTeacherArea(req(path),{});
assert.equal(r.status,503,'Fail closed without server secret');
assert.doesNotMatch(await r.text(),/Valutazione formativa e inclusione/);
r=await handleTeacherArea(req(path),env);
assert.equal(r.status,200);
assert.match(await r.text(),/Password di accesso/);
r=await handleTeacherArea(submit('password errata'),env);
assert.equal(r.status,401,'Reject invalid password');
r=await handleTeacherArea(submit(pass,'https://other.example'),env);
assert.equal(r.status,403,'Reject cross-origin form');
r=await handleTeacherArea(submit(pass),env);
assert.equal(r.status,303,'Accept valid password');
const cookie=r.headers.get('set-cookie');
assert.match(cookie,/HttpOnly/);
assert.match(cookie,/Secure/);
assert.match(cookie,/SameSite=Strict/);
const session=cookie.split(';')[0];
r=await handleTeacherArea(req(path,{headers:{Cookie:session}}),env);
assert.equal(r.status,200);
const page=await r.text();
assert.match(page,/Le insegnanti al centro/);
assert.match(page,/Cascina Favaglie/);
assert.match(r.headers.get('X-Robots-Tag'),/noindex/);
assert.equal(r.headers.get('Cache-Control'),'private, no-store, max-age=0');
r=await handleTeacherArea(req(path,{headers:{Cookie:session+'invalid'}}),env);
assert.match(await r.text(),/Password di accesso/);
r=await handleTeacherArea(req(path+'missing'),env);
assert.equal(r.status,404);
r=await handleTeacherArea(req(path+'logout',{method:'POST',headers:{Origin:base,'Sec-Fetch-Site':'same-origin',Cookie:session}}),env);
assert.equal(r.status,303);
assert.match(r.headers.get('set-cookie'),/Max-Age=0/);
console.log('Teacher area: authentication, origin check, cookie, cache, 404 and fail-closed tests passed');
